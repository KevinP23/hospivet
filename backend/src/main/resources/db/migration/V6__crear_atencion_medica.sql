CREATE TABLE atencion_medica (
    id_atencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT UNIQUE,
    id_mascota BIGINT NOT NULL,
    id_veterinario BIGINT NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    anamnesis VARCHAR(1000),
    observaciones VARCHAR(1000),
    CONSTRAINT fk_atencion_cita FOREIGN KEY (id_cita) REFERENCES cita (id_cita),
    CONSTRAINT fk_atencion_mascota FOREIGN KEY (id_mascota) REFERENCES mascota (id_mascota),
    CONSTRAINT fk_atencion_veterinario FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario)
);

CREATE INDEX idx_atencion_mascota_fecha ON atencion_medica (id_mascota, fecha_hora);

CREATE TABLE diagnostico (
    id_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atencion BIGINT NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    CONSTRAINT fk_diagnostico_atencion FOREIGN KEY (id_atencion) REFERENCES atencion_medica (id_atencion)
);

CREATE INDEX idx_diagnostico_atencion ON diagnostico (id_atencion);

CREATE TABLE tratamiento (
    id_tratamiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_diagnostico BIGINT NOT NULL,
    indicaciones VARCHAR(1000) NOT NULL,
    duracion VARCHAR(60),
    fecha_inicio DATE,
    fecha_fin DATE,
    CONSTRAINT fk_tratamiento_diagnostico FOREIGN KEY (id_diagnostico) REFERENCES diagnostico (id_diagnostico),
    CONSTRAINT ck_tratamiento_fechas CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE INDEX idx_tratamiento_diagnostico ON tratamiento (id_diagnostico);

CREATE TABLE receta (
    id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atencion BIGINT NOT NULL,
    medicamento VARCHAR(120) NOT NULL,
    dosis VARCHAR(60) NOT NULL,
    frecuencia VARCHAR(60) NOT NULL,
    duracion VARCHAR(60),
    indicaciones VARCHAR(255),
    CONSTRAINT fk_receta_atencion FOREIGN KEY (id_atencion) REFERENCES atencion_medica (id_atencion)
);

CREATE INDEX idx_receta_atencion ON receta (id_atencion);
