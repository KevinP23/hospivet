CREATE TABLE promocion (
    id_promocion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    porcentaje_descuento NUMERIC(5, 2) NOT NULL CHECK (porcentaje_descuento >= 0 AND porcentaje_descuento <= 100),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR', 'PUBLICADA', 'FINALIZADA')),
    CONSTRAINT ck_promocion_vigencia CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE promocion_producto (
    id_promocion BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    CONSTRAINT pk_promocion_producto PRIMARY KEY (id_promocion, id_producto),
    CONSTRAINT fk_promocion_producto_promocion FOREIGN KEY (id_promocion) REFERENCES promocion (id_promocion),
    CONSTRAINT fk_promocion_producto_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto)
);

CREATE TABLE promocion_servicio (
    id_promocion BIGINT NOT NULL,
    id_servicio BIGINT NOT NULL,
    CONSTRAINT pk_promocion_servicio PRIMARY KEY (id_promocion, id_servicio),
    CONSTRAINT fk_promocion_servicio_promocion FOREIGN KEY (id_promocion) REFERENCES promocion (id_promocion),
    CONSTRAINT fk_promocion_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES servicio (id_servicio)
);
