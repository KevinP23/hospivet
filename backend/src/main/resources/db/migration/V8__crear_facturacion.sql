CREATE TABLE factura (
    id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_veterinario BIGINT NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    descuento NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('EMITIDA', 'ANULADA', 'PAGADA')),
    CONSTRAINT fk_factura_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
    CONSTRAINT fk_factura_veterinario FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario),
    CONSTRAINT ck_factura_descuento CHECK (descuento >= 0 AND descuento <= subtotal),
    CONSTRAINT ck_factura_total CHECK (total = subtotal - descuento)
);

CREATE INDEX idx_factura_cliente ON factura (id_cliente);

CREATE TABLE detalle_factura (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura BIGINT NOT NULL,
    id_producto BIGINT,
    id_servicio BIGINT,
    descripcion VARCHAR(150) NOT NULL,
    cantidad BIGINT NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(12, 2) NOT NULL,
    tipo_item VARCHAR(10) NOT NULL CHECK (tipo_item IN ('PRODUCTO', 'SERVICIO')),
    CONSTRAINT fk_detalle_factura FOREIGN KEY (id_factura) REFERENCES factura (id_factura),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto),
    CONSTRAINT fk_detalle_servicio FOREIGN KEY (id_servicio) REFERENCES servicio (id_servicio),
    CONSTRAINT ck_detalle_item CHECK (
        (tipo_item = 'PRODUCTO' AND id_producto IS NOT NULL AND id_servicio IS NULL)
        OR (tipo_item = 'SERVICIO' AND id_servicio IS NOT NULL AND id_producto IS NULL)
    )
);

CREATE INDEX idx_detalle_factura ON detalle_factura (id_factura);

