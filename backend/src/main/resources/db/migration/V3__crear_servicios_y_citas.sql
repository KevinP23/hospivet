CREATE TABLE servicio (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    duracion_min INTEGER NOT NULL CHECK (duracion_min > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO servicio (nombre, descripcion, precio, duracion_min, activo)
SELECT 'Consulta general', 'Consulta veterinaria general', 0.00, 30, TRUE
WHERE NOT EXISTS (
    SELECT 1 FROM servicio WHERE nombre = 'Consulta general'
);

CREATE TABLE cita (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_mascota BIGINT NOT NULL,
    id_veterinario BIGINT NOT NULL,
    id_servicio BIGINT NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PROGRAMADA', 'ATENDIDA', 'CANCELADA')),
    motivo VARCHAR(255) NOT NULL,
    observaciones VARCHAR(255),
    CONSTRAINT fk_cita_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
    CONSTRAINT fk_cita_mascota FOREIGN KEY (id_mascota) REFERENCES mascota (id_mascota),
    CONSTRAINT fk_cita_veterinario FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario),
    CONSTRAINT fk_cita_servicio FOREIGN KEY (id_servicio) REFERENCES servicio (id_servicio)
);

CREATE INDEX idx_cita_veterinario_fecha ON cita (id_veterinario, fecha_hora);
CREATE INDEX idx_cita_cliente ON cita (id_cliente);
CREATE INDEX idx_cita_mascota ON cita (id_mascota);
